// Regenerates api/_certExamBank.ts from the lessons in src/courses.ts: the server's own copy of every check and
// its answer, so the certificate exam is graded on the server and never trusts the player's device.
// Run: node --experimental-strip-types --import ./scripts/ts-hooks.mjs scripts/gen-cert-exam.ts
import { writeFileSync } from 'node:fs'
import { COURSES } from '../src/courses.ts'
const bank = Object.fromEntries(COURSES.map((c) => [c.id, c.questions.map((q) => [q.prompt, q.choices, q.answer])]))
writeFileSync('api/_certExamBank.ts', `// GENERATED by scripts/gen-cert-exam.ts from src/courses.ts. Do not edit by hand.
// tests/cert.check.ts fails if this drifts from the lessons. [prompt, choices, index of the right choice]
export const EXAM_BANK: Record<string, Array<[string, string[], number]>> = ${JSON.stringify(bank)}
`)
console.log(Object.keys(bank).length, 'courses')
