"""Record Zahra's lines with a neural voice (Kokoro, voice af_heart) so she sounds the same on every phone.

    node --experimental-strip-types --import ./scripts/ts-hooks.mjs scripts/zahra-lines.ts > lines.json
    KOKORO_DIR=/path/to/model python3 scripts/gen-zahra-voice.py lines.json

KOKORO_DIR holds kokoro-v1.0.onnx and voices-v1.0.bin (github.com/thewh1teagle/kokoro-onnx releases).
Writes public/assets/voice/zahra/<key>.mp3 and src/zahraVoice.ts (the list of recorded keys). The key is a hash
of the normalised line, computed the same way in src/speech.ts, so an edited line simply falls back to the
device's voice until it is recorded again.
"""
import json, os, subprocess, sys, tempfile
import soundfile as sf
from kokoro_onnx import Kokoro

def norm(t: str) -> str:
    for a, b in (('’', "'"), ('‘', "'"), ('“', '"'), ('”', '"'), ('—', '-'), ('–', '-'), ('…', '...')):
        t = t.replace(a, b)
    return ' '.join(t.split()).strip().lower()

def key(t: str) -> str:
    h = 0x811C9DC5
    for ch in norm(t):
        h ^= ord(ch)
        h = (h * 0x01000193) & 0xFFFFFFFF
    return f'{h:08x}'

lines = json.load(open(sys.argv[1]))
model = os.environ.get('KOKORO_DIR', '.')
k = Kokoro(os.path.join(model, 'kokoro-v1.0.onnx'), os.path.join(model, 'voices-v1.0.bin'))
out = 'public/assets/voice/zahra'
os.makedirs(out, exist_ok=True)
keys = []
for i, line in enumerate(lines):
    kk = key(line)
    dst = f'{out}/{kk}.mp3'
    if not os.path.exists(dst):
        samples, sr = k.create(line, voice='af_heart', speed=0.97, lang='en-us')
        with tempfile.NamedTemporaryFile(suffix='.wav') as w:
            sf.write(w.name, samples, sr)
            subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', w.name, '-af', 'highpass=f=70,loudnorm=I=-16:TP=-1.5:LRA=7', '-ac', '1', '-ar', '24000', '-b:a', '48k', dst], check=True)
    keys.append(kk)
    print(f'{i + 1}/{len(lines)} {kk} {line[:60]}', flush=True)
with open('src/zahraVoice.ts', 'w') as f:
    f.write('// Generated by scripts/gen-zahra-voice.py: Zahra\'s recorded lines (public/assets/voice/zahra/<key>.mp3).\n')
    f.write('export const ZAHRA_CLIPS: ReadonlySet<string> = new Set(' + json.dumps(sorted(set(keys))) + ')\n')
