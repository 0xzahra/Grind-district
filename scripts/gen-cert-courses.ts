// Regenerates api/_certCourses.ts from src/logic.ts (server-side course titles and ranks for voucher checks).
import { writeFileSync } from 'node:fs'
import { SKILL_ORDER, SKILL_META, RANKS } from '../src/logic.ts'
const courses = Object.fromEntries(SKILL_ORDER.map((id) => [id, SKILL_META[id].title]))
writeFileSync('api/_certCourses.ts', `// GENERATED by scripts/gen-cert-courses.ts from src/logic.ts. Do not edit by hand.
// src/certs.check.ts fails if this drifts from SKILL_META / RANKS.
export const CERT_COURSES: Record<string, string> = ${JSON.stringify(courses, null, 2)}
export const CERT_RANKS: string[] = ${JSON.stringify(RANKS.map((r) => r.label))}
`)
console.log(Object.keys(courses).length, 'courses')
